#!/usr/bin/env node
// Generates realistic mixed traffic so the Grafana dashboard has something to show.
//
//   node scripts/load-test.mjs                         # local stack, 2 minutes
//   node scripts/load-test.mjs https://blogflow-web.onrender.com 60
//
// Mix: reads (most traffic), authenticated writes, plus deliberate 401/404/422s.

const BASE = (process.argv[2] || 'http://localhost:8080').replace(/\/$/, '');
const SECONDS = Number(process.argv[3] || 120);
const CONCURRENCY = Number(process.env.CONCURRENCY || 4);

const stats = { ok: 0, clientErr: 0, serverErr: 0, failed: 0 };

async function call(path, init = {}) {
  try {
    const res = await fetch(BASE + path, {
      ...init,
      headers: { 'Content-Type': 'application/json', ...init.headers },
    });
    if (res.status >= 500) stats.serverErr++;
    else if (res.status >= 400) stats.clientErr++;
    else stats.ok++;
    return res.headers.get('content-type')?.includes('json') ? res.json() : null;
  } catch {
    stats.failed++;
    return null;
  }
}

async function getToken() {
  const email = `load-${Date.now()}-${Math.random().toString(36).slice(2, 7)}@example.com`;
  const body = await call('/api/auth/register', {
    method: 'POST',
    body: JSON.stringify({ email, password: 'loadtest123', name: 'Load Tester' }),
  });
  return body?.data?.token;
}

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

async function worker(deadline) {
  const token = await getToken();
  const auth = token ? { Authorization: `Bearer ${token}` } : {};
  while (Date.now() < deadline) {
    const roll = Math.random();
    if (roll < 0.45) {
      await call(`/api/posts?page=${1 + Math.floor(Math.random() * 3)}&published=true`);
    } else if (roll < 0.7) {
      const id = 1 + Math.floor(Math.random() * 20);
      await call(`/api/posts/${id}`);
      await call(`/api/posts/${id}/comments`);
    } else if (roll < 0.8 && token) {
      const post = await call('/api/posts', {
        method: 'POST',
        headers: auth,
        body: JSON.stringify({ title: `Load test ${Date.now()}`, content: 'Generated by scripts/load-test.mjs', published: false }),
      });
      if (post?.data?.id) await call(`/api/posts/${post.data.id}`, { method: 'DELETE', headers: auth });
    } else if (roll < 0.87) {
      await call('/api/posts', { method: 'POST', body: '{}' }); // 401
    } else if (roll < 0.93) {
      await call(`/api/${pick(['nope', 'posts/999999', 'users/999999'])}`); // 404
    } else {
      await call('/api/auth/login', { method: 'POST', body: JSON.stringify({ email: 'bad', password: '' }) }); // 422
    }
    await new Promise((r) => setTimeout(r, 50 + Math.random() * 250));
  }
}

console.log(`Load testing ${BASE} for ${SECONDS}s with ${CONCURRENCY} workers…`);
const deadline = Date.now() + SECONDS * 1000;
const ticker = setInterval(() => console.log(JSON.stringify(stats)), 10000);
await Promise.all(Array.from({ length: CONCURRENCY }, () => worker(deadline)));
clearInterval(ticker);
console.log('Done:', stats);
